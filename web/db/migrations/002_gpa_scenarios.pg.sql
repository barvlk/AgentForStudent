-- AgentForStudent: saved GPA scenarios per student (PostgreSQL)
CREATE TABLE gpa_scenarios (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id  INTEGER NOT NULL REFERENCES students (student_id) ON DELETE CASCADE,
  name        TEXT    NOT NULL,
  scale       INTEGER NOT NULL CHECK (scale IN (4, 5)),
  prev_gpa    DOUBLE PRECISION NOT NULL CHECK (prev_gpa >= 0 AND prev_gpa <= 5),
  prev_hours  DOUBLE PRECISION NOT NULL CHECK (prev_hours >= 0),
  courses     TEXT    NOT NULL,  -- JSON: [{name, hours, letter}]
  result_gpa  DOUBLE PRECISION NOT NULL,
  created_at  BIGINT  NOT NULL
);
CREATE INDEX idx_gpa_scenarios_student ON gpa_scenarios (student_id, created_at);
